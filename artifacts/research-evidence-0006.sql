CREATE FUNCTION desk_research_context_shape() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF jsonb_typeof(NEW.content) IS DISTINCT FROM 'object'
  OR NEW.content->>'schema_version' IS DISTINCT FROM 'retained-source-evidence-v1'
  OR jsonb_typeof(NEW.content->'reports') IS DISTINCT FROM 'array'
  OR jsonb_array_length(NEW.content->'reports') NOT BETWEEN 1 AND 16
  OR (NEW.content->>'cutoff')::timestamptz IS DISTINCT FROM NEW.created_at
  OR octet_length(NEW.content::text)>131072 THEN
  RAISE EXCEPTION 'research evidence requires bounded exact inputs' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER desk_research_context_shape BEFORE INSERT ON macro_desk_researchevidencecontext
 FOR EACH ROW EXECUTE FUNCTION desk_research_context_shape();
CREATE FUNCTION desk_research_member_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE selected jsonb; packet macro_desk_researchevidencecontext%ROWTYPE;
 revision macro_monitoring_sourcerevision%ROWTYPE; report macro_monitoring_sourcereport%ROWTYPE;
 contract macro_desk_sourcecontractversion%ROWTYPE; witness macro_monitoring_durableobservation%ROWTYPE;
BEGIN
 SELECT * INTO STRICT packet FROM macro_desk_researchevidencecontext WHERE id=NEW.context_id;
 SELECT * INTO STRICT revision FROM macro_monitoring_sourcerevision WHERE id=NEW.revision_id;
 SELECT * INTO STRICT report FROM macro_monitoring_sourcereport WHERE id=revision.report_id;
 SELECT * INTO STRICT contract FROM macro_desk_sourcecontractversion WHERE id=NEW.contract_id;
 SELECT * INTO STRICT witness FROM macro_monitoring_durableobservation WHERE revision_id=NEW.witness_id;
 SELECT item INTO selected FROM jsonb_array_elements(packet.content->'reports') item
  WHERE item->>'revision_id'=NEW.revision_id::text;
 IF selected IS NULL OR contract.source_id IS DISTINCT FROM report.source_id
  OR NEW.witness_id IS DISTINCT FROM NEW.revision_id
  OR NEW.head_at_admission_id IS DISTINCT FROM NEW.revision_id
  OR report.current_revision_id IS DISTINCT FROM NEW.revision_id
  OR NOT contract.permitted OR witness.observed_by_at>packet.created_at
  OR contract.observed_at>packet.created_at
  OR selected->>'source_id' IS DISTINCT FROM report.source_id
  OR selected->>'contract_version_id' IS DISTINCT FROM NEW.contract_id::text
  OR selected->>'contract_digest' IS DISTINCT FROM contract.digest
  OR selected->>'head_at_admission_id' IS DISTINCT FROM NEW.head_at_admission_id::text
  OR selected->>'title' IS DISTINCT FROM revision.payload->>'title'
  OR selected->>'content' IS DISTINCT FROM revision.payload->>'content'
  OR selected->>'source_url' IS DISTINCT FROM revision.payload->>'url'
  OR selected->'source_claimed_published_at' IS DISTINCT FROM revision.payload->'published_at'
  OR (selected->>'system_received_at')::timestamptz IS DISTINCT FROM revision.system_received_at
  OR (selected->>'availability_witness_at')::timestamptz IS DISTINCT FROM witness.observed_by_at
  OR NOT EXISTS (SELECT 1 FROM macro_desk_sourcecontracthead WHERE source_id=report.source_id AND version_id=NEW.contract_id)
 THEN RAISE EXCEPTION 'research member differs from protected retained evidence' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER desk_research_member_guard BEFORE INSERT ON macro_desk_researchevidencemember
 FOR EACH ROW EXECUTE FUNCTION desk_research_member_guard();
CREATE FUNCTION desk_research_complete() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE identity uuid; selected_count integer; member_count integer;
BEGIN
 IF TG_TABLE_NAME='macro_desk_researchevidencecontext' THEN identity := NEW.id;
 ELSE identity := NEW.context_id; END IF;
 SELECT jsonb_array_length(content->'reports') INTO STRICT selected_count
  FROM macro_desk_researchevidencecontext WHERE id=identity;
 SELECT count(*) INTO member_count FROM macro_desk_researchevidencemember WHERE context_id=identity;
 IF selected_count IS DISTINCT FROM member_count THEN
  RAISE EXCEPTION 'research evidence requires complete relational membership' USING ERRCODE='23514';
 END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER desk_research_complete_context AFTER INSERT ON macro_desk_researchevidencecontext
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION desk_research_complete();
CREATE CONSTRAINT TRIGGER desk_research_complete_member AFTER INSERT ON macro_desk_researchevidencemember
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION desk_research_complete();

